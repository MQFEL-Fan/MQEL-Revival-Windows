def ldstr_tokens(code):
    toks = []
    i, n = 0, len(code)
    while i < n:
        op = code[i]; i += 1
        if op == 0xFE:
            if i >= n: break
            i += TWO.get(code[i], 4) + 1
            continue
        if op == 0x72:
            if i + 4 <= n:
                toks.append(struct.unpack('<I', code[i:i+4])[0])
            i += 4
            continue
        sz = ONE.get(op)
        if sz is None:
            toks.append(f'<unknown-op-0x{op:02x}-at-{i-1}>')
            break
        if op == 0x45:
            if i + 4 > n: break
            i += 4 + struct.unpack('<I', code[i:i+4])[0] * 4
        else:
            i += sz
    return toks

def code_only(raw):
    raw = bytes(raw)
    if len(raw) < 8: return b''
    b0 = raw[0]
    if (b0 & 0x7) == 0x2:
        return raw[1:1 + (b0 >> 2)]
    hsz = ((struct.unpack('<H', raw[:2])[0] >> 12)) * 4
    csz = struct.unpack('<I', raw[4:8])[0]
    return raw[hsz:hsz + csz]

def main():
    path = sys.argv[1]
    filt = sys.argv[2] if len(sys.argv) > 2 else ''
    mode = sys.argv[3] if len(sys.argv) > 3 else 'all'
    pe = dotnetfile.DotNetPE(path)
    types = pe.TypeDef.get_type_names_with_methods()

    def match(full):
        return not filt or filt.lower() in full.lower()

    if mode in ('all', 'types'):
        for t in types:
            full = f'{t.Namespace}.{t.Type}' if t.Namespace else t.Type
            if not match(full): continue
            print(f'### {full}')
            for m in t.Methods:
                print(f'    - {m.Name} rva=0x{m.RVA:x} code={m.CodeSize}')

    if mode in ('all', 'ldstr'):
        print('########## ldstr ##########')
        for t in types:
            full = f'{t.Namespace}.{t.Type}' if t.Namespace else t.Type
            if not match(full): continue
            for m in t.Methods:
                code = code_only(m.RawBytes)
                if not code: continue
                toks = ldstr_tokens(code)
                out = []
                for tok in toks:
                    if isinstance(tok, str):
                        out.append(tok); continue
                    if (tok & 0xFF000000) == 0x70000000:
                        try: out.append(pe.get_user_string(tok & 0xFFFFFF))
                        except Exception as e: out.append(f'<US-err {tok:08x}>')
                if out:
                    print(f'{full}.{m.Name}:')
                    for s in out: print(f'    |{s}')

if __name__ == '__main__':
    main()
